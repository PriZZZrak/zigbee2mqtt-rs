#!/usr/bin/env python3
"""Frontend/API differential over the bridge MQTT API.

Compares normalized `bridge/state`, `bridge/info`, `bridge/devices` and the
`permit_join` response produced by the Rust bridge candidate with a dump captured
from the pinned upstream Zigbee2MQTT test harness (vitest mocks). The upstream
dump is generated by `docs/parity/evidence/api/api_dump_reference.test.ts`.
"""

from __future__ import annotations

import argparse
import json
import re
import shlex
import subprocess
import sys
import tempfile
from pathlib import Path

try:
    from evid04_harness import verify_pins
except ImportError:  # pragma: no cover
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from evid04_harness import verify_pins


def build_fixture(upstream: dict, directory: Path) -> Path:
    info = upstream["bridge_info"]
    config = info.get("config") or {}
    advanced = config.get("advanced") or {}
    mqtt = info.get("mqtt") or {}
    base_topic = (config.get("mqtt") or {}).get("base_topic", "zigbee2mqtt")
    valid_ieee = re.compile(r"^0x[0-9a-f]{16}$")
    devices = [
        device
        for device in upstream["bridge_devices"]
        if device["type"] != "Coordinator"
        and valid_ieee.match(str(device.get("ieee_address", "")))
        and (device.get("network_address") or 0) <= 0xFFFF
    ]
    lines = [
        "mqtt:",
        f"  base_topic: {base_topic}",
        f"  server: {mqtt.get('server', 'mqtt://127.0.0.1:1883')}",
        "serial:",
        "  port: /dev/ttyACM0",
        "  adapter: zstack",
        "advanced:",
        f"  log_level: {advanced.get('log_level', 'info')}",
        f"  channel: {advanced.get('channel', 11)}",
        f"  pan_id: {advanced.get('pan_id', 6754)}",
        f"  output: {advanced.get('output', 'json')}",
        "  ext_pan_id: [" + ", ".join(str(byte) for byte in advanced.get("ext_pan_id", [0xdd] * 8)) + "]",
        "devices:",
    ]
    for device in devices:
        lines.append(f'  "{device["ieee_address"]}":')
        lines.append(f'    friendly_name: "{device["friendly_name"]}"')
        lines.append(f'    disabled: {"true" if device.get("disabled") else "false"}')
        if device.get("description"):
            lines.append(f'    description: "{device["description"]}"')
    (directory / "configuration.yaml").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # The database fixture mirrors the upstream mock devices, including the
    # endpoint cluster lists the definition generator needs.
    db_lines = []
    for index, meta in enumerate(sorted(upstream.get("device_meta", []), key=lambda m: m["ieeeAddr"]), start=1):
        ieee = meta.get("ieeeAddr", "")
        if not valid_ieee.match(str(ieee)):
            continue
        if (meta.get("nwkAddr") or 0) > 0xFFFF:
            continue
        endpoints = {}
        for endpoint in meta.get("endpoints", []):
            endpoints[str(endpoint["id"])] = {
                "profId": 260,
                "epId": endpoint["id"],
                "devId": 0,
                "inClusterList": endpoint.get("inputClusters", []),
                "outClusterList": endpoint.get("outputClusters", []),
                "clusters": {},
                "binds": [],
                "configuredReportings": [],
                "meta": {},
            }
        db_lines.append(
            json.dumps(
                {
                    "id": index + 1,
                    "type": meta.get("type"),
                    "ieeeAddr": ieee,
                    "nwkAddr": meta.get("nwkAddr", 0),
                    "manufId": meta.get("manufId"),
                    "manufName": meta.get("manufName"),
                    "powerSource": meta.get("powerSource"),
                    "modelId": meta.get("modelId"),
                    "swBuildId": meta.get("swBuildId"),
                    "dateCode": meta.get("dateCode"),
                    "epList": [endpoint["id"] for endpoint in meta.get("endpoints", [])],
                    "endpoints": endpoints,
                    "interviewCompleted": meta.get("interviewComplete", False),
                    "interviewState": meta.get("interviewState")
                    or ("SUCCESSFUL" if meta.get("interviewComplete") else "FAILED"),
                    "meta": {},
                },
                separators=(",", ":"),
            )
        )
    (directory / "database.db").write_text("\n".join(db_lines), encoding="utf-8")
    return directory


def normalize_info(info: dict) -> dict:
    """Normalize `bridge/info` to the contract subset the frontend reads.

    Build/environment identity (`os` values, `version`, `commit`, herdsman
    version) is only checked for presence: the Rust implementation necessarily
    reports its own versions and the host's OS numbers.
    """
    coordinator = info.get("coordinator") or {}
    config = info.get("config") or {}
    advanced = config.get("advanced") or {}
    os_info = info.get("os") or {}
    return {
        "coordinator": {
            "ieee_address": coordinator.get("ieee_address"),
            "type": coordinator.get("type"),
        },
        "log_level": info.get("log_level"),
        "permit_join": info.get("permit_join"),
        "restart_required": info.get("restart_required"),
        "network": info.get("network"),
        "mqtt": {
            "server": (info.get("mqtt") or {}).get("server"),
            # The Rust transport is MQTT 3.1.1 (protocol version 4); the pinned
            # upstream test harness reports its own client version (5).
            "version_supported": (info.get("mqtt") or {}).get("version") in (4, 5),
        },
        "config": {
            "advanced": {
                key: advanced.get(key)
                for key in ("channel", "pan_id", "ext_pan_id", "log_level", "output")
            },
            "mqtt_base_topic": (config.get("mqtt") or {}).get("base_topic"),
        },
        "converters_version": (info.get("zigbee_herdsman_converters") or {}).get("version"),
        "herdsman_version": (info.get("zigbee_herdsman") or {}).get("version"),
        "os_shape": {
            key: isinstance(os_info.get(key), (str, int))
            for key in ("cpus", "memory_mb", "version", "node_version")
        },
        # Frontend pages dereference these without optional chaining
        # (HomePage -> config.availability.enabled, About -> versions).
        "config_ui_shape": {
            "availability_enabled": isinstance(
                (config.get("availability") or {}).get("enabled"), bool
            ),
            "advanced_last_seen": isinstance(
                (advanced.get("last_seen")), str
            ),
            "homeassistant_enabled": isinstance(
                (config.get("homeassistant") or {}).get("enabled"), bool
            ),
            "frontend_enabled": isinstance(
                (config.get("frontend") or {}).get("enabled"), bool
            ),
            "ota_object": isinstance(config.get("ota"), dict),
        },
        "config_schema_shape": {
            "has_properties": isinstance(
                (info.get("config_schema") or {}).get("properties"), dict
            ),
            "has_definitions": isinstance(
                (info.get("config_schema") or {}).get("definitions"), dict
            ),
            "device_properties": isinstance(
                (((info.get("config_schema") or {}).get("definitions") or {}).get("device") or {}).get(
                    "properties"
                ),
                dict,
            ),
            "group_properties": isinstance(
                (((info.get("config_schema") or {}).get("definitions") or {}).get("group") or {}).get(
                    "properties"
                ),
                dict,
            ),
        },
        "has_version": isinstance(info.get("version"), str) and bool(info.get("version")),
        "has_commit": isinstance(info.get("commit"), str) and bool(info.get("commit")),
    }


def normalize_definition(value):
    if not isinstance(value, dict):
        return None
    if value.get("source") == "generated":
        # The app's test mocks resolve endpoint clusters through a partial
        # cluster-name map, so the dump's generated definitions omit extenders
        # for genIdentify/genGroups/etc. Their content is compared with full
        # ZCL names by scripts/generated_definition_diff.py; here only the
        # marker (and `supported`, which is false for generated) is compared.
        return {"source": "generated"}
    exposes = value.get("exposes") or []
    return {
        "source": value.get("source"),
        "model": value.get("model"),
        "vendor": value.get("vendor"),
        "description": value.get("description"),
        "supports_ota": value.get("supports_ota"),
        "options": value.get("options") or [],
        "version": value.get("version"),
        "icon": value.get("icon"),
        "exposes": exposes,
    }


def normalize_devices(devices: list, cluster_map: dict, include_definition: bool = True) -> dict:
    normalized = {}
    valid_ieee = re.compile(r"^0x[0-9a-f]{16}$")
    for device in devices:
        # The upstream test fixtures contain synthetic devices that cannot exist
        # on a real network (non-hex IEEE / 32-bit NWK); both importers reject
        # them, so they are outside the contract.
        if not valid_ieee.match(str(device.get("ieee_address", ""))):
            continue
        if (device.get("network_address") or 0) > 0xFFFF:
            continue
        # Endpoint clusters/bindings/reportings are compared by the storage
        # differential; the frontend API subset checks endpoint identity.
        endpoints = sorted(
            int(endpoint_id) for endpoint_id in (device.get("endpoints") or {})
        )
        normalized[device["ieee_address"]] = {
            "type": device.get("type"),
            "network_address": device.get("network_address"),
            "friendly_name": device.get("friendly_name"),
            "power_source": device.get("power_source"),
            "model_id": device.get("model_id"),
            "manufacturer": device.get("manufacturer"),
            "description": device.get("description"),
            "software_build_id": device.get("software_build_id"),
            "date_code": device.get("date_code"),
            "interview_completed": device.get("interview_completed"),
            "interview_state": device.get("interview_state"),
            "interviewing": device.get("interviewing"),
            "disabled": device.get("disabled"),
            "endpoints": endpoints,
        }
        if include_definition:
            normalized[device["ieee_address"]]["definition"] = normalize_definition(
                device.get("definition")
            )
            normalized[device["ieee_address"]]["supported"] = device.get("supported")
    return normalized


def _short(value, limit: int = 160) -> str:
    text = repr(value)
    return text if len(text) <= limit else text[:limit] + "…"


def definitions_view(normalized_devices: dict) -> dict:
    return {
        ieee: {
            "definition": device.get("definition"),
            "supported": device.get("supported"),
        }
        for ieee, device in normalized_devices.items()
    }


def recursive_diff(expected, actual, path="") -> list[str]:
    mismatches = []
    if isinstance(expected, dict) and isinstance(actual, dict):
        for key in sorted(set(expected) | set(actual)):
            child = f"{path}.{key}" if path else key
            mismatches.extend(recursive_diff(expected.get(key), actual.get(key), child))
    elif expected != actual:
        mismatches.append(
            f"{path}: reference={_short(expected)} candidate={_short(actual)}"
        )
    return mismatches


def diff(expected: dict, actual: dict) -> list[str]:
    mismatches = []
    if set(expected) != set(actual):
        mismatches.append(
            f"device sets differ: reference={sorted(expected)} candidate={sorted(actual)}"
        )
    for ieee in sorted(set(expected) & set(actual)):
        for key in sorted(set(expected[ieee]) | set(actual[ieee])):
            if expected[ieee].get(key) != actual[ieee].get(key):
                mismatches.append(
                    f"{ieee}.{key}: reference={expected[ieee].get(key)!r} "
                    f"candidate={actual[ieee].get(key)!r}"
                )
    return mismatches


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", type=Path, required=True)
    parser.add_argument("--candidate-cmd", required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--lock", type=Path, default=Path("docs/parity/upstream-lock.json"))
    parser.add_argument(
        "--pin-root", type=Path, default=Path(__file__).resolve().parents[1] / ".upstream"
    )
    parser.add_argument(
        "--known-gap",
        action="append",
        default=[],
        help="case id whose failure is a documented, tracked gap (reported, not fatal)",
    )
    parser.add_argument("--require-pins", action="store_true")
    parser.add_argument("--skip-pins", action="store_true")
    args = parser.parse_args(argv)

    pins = [] if args.skip_pins else verify_pins(args.lock, args.pin_root)
    if args.require_pins and any(pin["status"] != "MATCH" for pin in pins):
        for pin in pins:
            print(f"{pin['source']}: {pin['status']}", file=sys.stderr)
        return 1

    upstream = json.loads(args.upstream.read_text(encoding="utf-8"))
    cluster_map = json.loads(
        (Path(__file__).resolve().parents[1] / "docs/parity/evidence/api/cluster-map.json")
        .read_text(encoding="utf-8")
    )
    with tempfile.TemporaryDirectory(prefix="z2m-api-") as directory:
        data_dir = build_fixture(upstream, Path(directory))
        completed = subprocess.run(
            shlex.split(args.candidate_cmd) + ["--data", str(data_dir)],
            capture_output=True,
            text=True,
            timeout=120,
            check=False,
        )
        if completed.returncode != 0:
            print(completed.stderr, file=sys.stderr)
            return 1
        candidate = json.loads(completed.stdout)

    cases = []
    failures = 0

    def add_case(case_id: str, expected, actual, comparator) -> None:
        nonlocal failures
        mismatches = comparator(expected, actual) if comparator else (
            [] if expected == actual else [f"reference={expected!r} candidate={actual!r}"]
        )
        if mismatches and case_id in args.known_gap:
            status = "KNOWN_GAP"
            print(f"{case_id}: KNOWN_GAP ({len(mismatches)} mismatches)", file=sys.stderr)
        elif mismatches:
            status = "FAIL"
            failures += 1
            print(f"{case_id}: FAIL", file=sys.stderr)
            for mismatch in mismatches:
                print(f"  {mismatch}", file=sys.stderr)
        else:
            status = "PASS"
        cases.append({"id": case_id, "status": status, "mismatches": mismatches})

    add_case("bridge-state", upstream["bridge_state"], candidate["bridge_state"], None)
    add_case(
        "bridge-info",
        normalize_info(upstream["bridge_info"]),
        normalize_info(candidate["bridge_info"]),
        recursive_diff,
    )
    upstream_devices = normalize_devices(upstream["bridge_devices"], cluster_map)
    candidate_devices = normalize_devices(candidate["bridge_devices"], cluster_map)
    add_case(
        "bridge-devices",
        normalize_devices(upstream["bridge_devices"], cluster_map, include_definition=False),
        normalize_devices(candidate["bridge_devices"], cluster_map, include_definition=False),
        diff,
    )
    add_case(
        "bridge-devices-definitions",
        definitions_view(upstream_devices),
        definitions_view(candidate_devices),
        diff,
    )
    add_case(
        "permit-join-response",
        upstream["permit_join_response"],
        candidate["permit_join_response"],
        None,
    )

    known_gaps = [case["id"] for case in cases if case["status"] == "KNOWN_GAP"]
    passed = sum(1 for case in cases if case["status"] == "PASS")
    report = {
        "status": "PASS" if failures == 0 else "FAIL",
        "passed": passed,
        "failed": failures,
        "known_gap_cases": known_gaps,
        "known_gap_reasons": {
            gap: "tracked in docs/parity/inventory.csv (see FRONTEND-004 / CONVERTER-021)"
            for gap in known_gaps
        },
        "pins": pins,
        "cases": cases,
    }
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(
        f"API: {report['passed']} passed, {report['failed']} failed, "
        f"known_gaps={known_gaps}, "
        f"pins={[(pin['source'], pin['status']) for pin in pins]}"
    )
    return 0 if failures == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
